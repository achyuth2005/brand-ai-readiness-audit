"""Phase 5 -- PROACTIVE RECOMMENDATIONS. Improvements where no defect was found.

The brief rewards suggestions that "go beyond the problems found" and are "relevant and
non-obvious". Two failure modes are designed against:

* **Generic advice** ("add more content", "improve page speed") is not specific, not
  mechanism-sound and not evidence-linked. Every recommendation here carries a rationale
  grounded in something observed on *this* site, a mechanism, and a verification step.
* **Fabricated defects** -- advice dressed as findings to inflate the count -- damage
  detection accuracy. So recommendations live in their own top-level array, carry
  ``is_defect: false``, and never enter the severity counts.

Four generators, in ascending order of how site-specific they are:

1. **near_miss**  -- a check measured something just under its threshold. The most
   credible advice available, because the number is a measurement of this site.
2. **posture_gap** -- a check passed because something exists, but only shallowly.
3. **profile_playbook** -- type-conditional improvements, each gated on the site not
   already having the thing, and each carrying a mechanism sentence.
4. **leverage_synthesis** -- reasoning over the *combination* of findings: a single
   template causing most of them, drift-prone defects that need a process fix, and the
   measurement loop that keeps discoverability monitored.
"""

