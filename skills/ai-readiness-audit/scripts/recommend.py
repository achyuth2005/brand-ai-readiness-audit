def near_misses(facts: _Facts, margin: float) -> List[Dict[str, Any]]:
    out = []
    seen = set()
    for item in facts.near:
        check_id = item["check_id"]
        if facts.reported(check_id) or check_id in seen:
            continue
        if item.get("proximity", 1.0) > margin and item.get("threshold"):
            continue
        seen.add(check_id)
        advice = NEAR_MISS_ADVICE.get(check_id)
        meta = checks.meta(check_id)
        examples = item.get("examples") or []
        rationale = (f"Not a defect. {item['metric']} measured {item['value']} against a "
                     f"threshold of {item['threshold']}. {item.get('detail', '')}"
                     + (f" Examples: {'; '.join(examples[:3])}." if examples else ""))
        if advice is None:
            out.append(_rec("near_miss", f"Close the near miss on {check_id}",
                            meta["category"], meta["gate"], rationale, meta["summary"],
                            ["Address the measurement above before it crosses the "
                             "threshold."],
                            "Re-run the audit and confirm the measurement moves away from "
                            "the threshold.", priority="low",
                            measurement={k: item[k] for k in ("metric", "value",
                                                              "threshold")}))
            continue
        out.append(_rec("near_miss", advice["title"], advice["category"], meta["gate"],
                        rationale, advice["mechanism"], advice["implementation"],
                        advice["verification"], priority="medium",
                        effort=advice["effort"], owner=advice["owner"],
                        measurement={k: item[k] for k in ("metric", "value", "threshold")}))
    return out


