def generate(merged: Dict[str, Any], profile: SiteProfile, ledger: Any,
             config: Dict[str, Any]) -> List[Dict[str, Any]]:
    facts = _Facts(ledger, merged, profile)
    margin = float(bootstrap.threshold(config, "false_positive_control.near_miss_margin", 0.2))
    cap = int(bootstrap.threshold(config, "recommendations.max_recommendations", 14))

    recs = leverage(facts, config) + near_misses(facts, margin) + posture_gaps(facts) \
        + playbooks(facts)
    unique: Dict[str, Dict[str, Any]] = {}
    for rec in recs:
        unique.setdefault(rec["title"], rec)
    ordered = sorted(unique.values(), key=lambda r: (
        PRIORITY_ORDER.get(r["priority"], 9), GENERATOR_ORDER.get(r["generator"], 9),
        r["title"]))[:cap]
    for index, rec in enumerate(ordered, start=1):
        rec["id"] = f"R-{index:03d}"
    return ordered


def main(argv: Optional[Sequence[str]] = None) -> int:
    import argparse
    from auditkit.ledger import Ledger
    parser = argparse.ArgumentParser(description="Generate proactive recommendations.")
    parser.add_argument("--merged", required=True, type=Path)
    parser.add_argument("--profile", required=True, type=Path)
    parser.add_argument("--ledger", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args(argv)
    merged = json.loads(args.merged.read_text(encoding="utf-8"))
    profile = SiteProfile.from_dict(json.loads(args.profile.read_text(encoding="utf-8")))
    recs = generate(merged, profile, Ledger.open(args.ledger), bootstrap.load_config())
    args.out.write_text(json.dumps(recs, indent=2, sort_keys=True, ensure_ascii=False)
                        + "\n", encoding="utf-8")
    print(f"recommendations: {len(recs)}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
