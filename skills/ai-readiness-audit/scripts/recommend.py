class _Facts:
    """Observations about the crawl, gathered once, used to gate every recommendation."""

    def __init__(self, ledger: Any, merged: Dict[str, Any], profile: SiteProfile):
        self.ledger = ledger
        self.merged = merged
        self.profile = profile
        self.pages = ledger.pages() if ledger is not None else []
        self.paths = sorted({urlnorm.try_normalise(e.final_url or e.url).path
                             for e in self.pages
                             if urlnorm.try_normalise(e.final_url or e.url)})
        self.active = {f["check_id"] for f in merged.get("findings", [])}
        self.masked = {f["check_id"] for f in merged.get("masked_findings", [])}
        self.near = merged.get("near_misses", [])
        self.posture = merged.get("posture", {})

    def has_path(self, pattern: str) -> bool:
        regex = re.compile(pattern, re.IGNORECASE)
        return any(regex.search(p) for p in self.paths)

    def reported(self, *check_ids: str) -> bool:
        return any(c in self.active or c in self.masked for c in check_ids)

    def ledger_ok(self, path: str) -> Optional[bool]:
        """True/False when the path was requested; None when it never was."""
        if self.ledger is None:
            return None
        for entry in self.ledger.entries():
            normal = urlnorm.try_normalise(entry.url.split("#")[0])
            if normal is not None and normal.path == path:
                return entry.ok
        return None

    def pricing_has_prices(self) -> Optional[bool]:
        pricing = [e for e in self.pages
                   if "pricing" in urlnorm.path_classes(urlnorm.try_normalise(e.url))]
        if not pricing:
            return None
        doc = Document(self.ledger.text(pricing[0]))
        return bool(textnorm.find_all_money(doc.main_text()))


def _rec(generator: str, title: str, category: str, gate: str, rationale: str,
         mechanism: str, implementation: Sequence[str], verification: str, *,
         priority: str = "medium", effort: str = "low", owner: str = "",
         expected: str = "", measurement: Optional[Dict[str, Any]] = None,
         calibration: str = "") -> Dict[str, Any]:
    rec: Dict[str, Any] = {
        "id": "", "title": title, "category": category, "gate": gate,
        "generator": generator, "rationale": rationale, "mechanism": mechanism,
        "expected_effect": expected, "priority": priority, "effort": effort,
        "owner_role": owner, "implementation": list(implementation),
        "verification": verification, "is_defect": False,
    }
    if measurement:
        rec["measurement"] = measurement
    if calibration:
        rec["calibration"] = calibration
    return rec


